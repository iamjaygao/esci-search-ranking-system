"""Section 14 -- OLD (large_version) vs NEW (small_version / Task 1) benchmark definitions."""
import json
import os
import sys

import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from task1_common import BASE  # noqa: E402

# Table 2 of the brief -- large_version==1, confirms the OLD benchmark's identity
LARGE = {
    "overall": {"total_q": 130652, "total_j": 2621288, "train_q": 99684,
                "train_j": 1983272, "test_q": 30969, "test_j": 638016},
    "us": {"total_q": 97345, "total_j": 1818825, "train_q": 74888,
           "train_j": 1393063, "test_q": 22458, "test_j": 425762},
    "es": {"total_q": 15180, "total_j": 356410, "train_q": 11336,
           "train_j": 263063, "test_q": 3844, "test_j": 93347},
    "jp": {"total_q": 18127, "total_j": 446053, "train_q": 13460,
           "train_j": 327146, "test_q": 4667, "test_j": 118907},
}


def main():
    counts = json.load(open(os.path.join(BASE, "task1_dataset_counts.json")))
    obs = counts["observed"]
    deg = json.load(open(os.path.join(BASE, "degenerate_query_analysis.json")))

    large_test_q = LARGE["overall"]["test_q"]
    new_test_q = obs["overall"]["test_q"]
    large_w = {lc: round(LARGE[lc]["test_q"] / large_test_q, 4) for lc in ["us", "es", "jp"]}
    new_w = {lc: round(obs[lc]["test_q"] / new_test_q, 4) for lc in ["us", "es", "jp"]}
    large_rw = {lc: round(LARGE[lc]["test_j"] / LARGE["overall"]["test_j"], 4)
                for lc in ["us", "es", "jp"]}
    new_rw = {lc: round(obs[lc]["test_j"] / obs["overall"]["test_j"], 4)
              for lc in ["us", "es", "jp"]}
    large_depth = {lc: round(LARGE[lc]["test_j"] / LARGE[lc]["test_q"], 2)
                   for lc in ["us", "es", "jp"]}
    large_depth["overall"] = round(LARGE["overall"]["test_j"] / large_test_q, 2)

    L = []
    L.append("# Benchmark Definition Comparison — OLD (large_version) vs NEW (Task 1)\n")
    L.append("Generated by `scripts/make_benchmark_comparison.py`. "
             "Every NEW figure is measured; every OLD figure is Table 2 of the brief, "
             "independently confirmed against the raw parquet.\n")

    L.append("## 1. Headline\n")
    L.append("| | OLD | NEW |")
    L.append("|---|---|---|")
    L.append("| version flag | `large_version == 1` | `small_version == 1` |")
    L.append("| corresponding task | KDD Cup 2022 Task 2 / 3 | **KDD Cup 2022 Task 1** |")
    L.append(f"| test queries | {large_test_q:,} | **{new_test_q:,}** |")
    L.append(f"| test rows | {LARGE['overall']['test_j']:,} | **{obs['overall']['test_j']:,}** |")
    L.append(f"| test avg depth | {large_depth['overall']:.2f} | "
             f"**{obs['overall']['test_depth']:.2f}** |")
    L.append(f"| train queries | {LARGE['overall']['train_q']:,} | {obs['overall']['train_q']:,} |")
    L.append(f"| train rows | {LARGE['overall']['train_j']:,} | {obs['overall']['train_j']:,} |")
    L.append("| headline metric | NDCG@10 | **full-list NDCG** |")
    L.append("| gain convention | `2**rel-1` on {E:1.0,S:0.1,C:0.01,I:0} then, in Phase 1.1, "
             "linear E/S/C/I | linear E=1.0 S=0.1 C=0.01 I=0 |")
    L.append("| scorer | `official_metric_final/scripts/official_kdd_ndcg.py` | "
             "`kdd_task1_benchmark/scripts/kdd_task1_ndcg.py` |")
    L.append("| candidate_pool tag | `large_v1` | `task1_small_v1` |")
    L.append("| comparable to the KDD Task 1 leaderboard | **no** | see section 15 of the REPORT |")
    L.append("")

    L.append("## 2. Locale composition\n")
    L.append("### Test-set query weights (this is the change that mechanically moves NDCG)\n")
    L.append("| locale | OLD weight | NEW weight | shift |")
    L.append("|---|---:|---:|---:|")
    for lc in ["us", "es", "jp"]:
        L.append(f"| {lc.upper()} | {large_w[lc]:.4f} | {new_w[lc]:.4f} | "
                 f"{new_w[lc]-large_w[lc]:+.4f} |")
    L.append("")
    L.append("### Test-set row weights\n")
    L.append("| locale | OLD | NEW | shift |")
    L.append("|---|---:|---:|---:|")
    for lc in ["us", "es", "jp"]:
        L.append(f"| {lc.upper()} | {large_rw[lc]:.4f} | {new_rw[lc]:.4f} | "
                 f"{new_rw[lc]-large_rw[lc]:+.4f} |")
    L.append("")
    L.append("### Test-set candidate depth\n")
    L.append("| locale | OLD depth | NEW depth | shift |")
    L.append("|---|---:|---:|---:|")
    for lc in ["us", "es", "jp"]:
        L.append(f"| {lc.upper()} | {large_depth[lc]:.2f} | {obs[lc]['test_depth']:.2f} | "
                 f"{obs[lc]['test_depth']-large_depth[lc]:+.2f} |")
    L.append(f"| **overall** | {large_depth['overall']:.2f} | "
             f"{obs['overall']['test_depth']:.2f} | "
             f"{obs['overall']['test_depth']-large_depth['overall']:+.2f} |")
    L.append("")
    L.append("Explicit test query-weight shift, as required by section 14:\n")
    L.append("```")
    for lc in ["us", "es", "jp"]:
        L.append(f"{lc.upper():3s} {large_w[lc]:.4f} -> {new_w[lc]:.4f}")
    L.append("```\n")
    L.append("JP carries the largest weight increase and is also the locale every model is "
             "weakest on, so the reduced version is arithmetically harder before any query-"
             "difficulty effect is considered.\n")

    L.append("## 3. Per-locale absolute counts\n")
    L.append("| locale | OLD test q | NEW test q | OLD test rows | NEW test rows |")
    L.append("|---|---:|---:|---:|---:|")
    for lc in ["us", "es", "jp"]:
        L.append(f"| {lc.upper()} | {LARGE[lc]['test_q']:,} | {obs[lc]['test_q']:,} | "
                 f"{LARGE[lc]['test_j']:,} | {obs[lc]['test_j']:,} |")
    L.append(f"| **overall** | {large_test_q:,} | {new_test_q:,} | "
             f"{LARGE['overall']['test_j']:,} | {obs['overall']['test_j']:,} |")
    L.append("")

    L.append("## 4. Query difficulty\n")
    dc = deg["large_version_comparison"]
    L.append("| | OLD test | NEW test |")
    L.append("|---|---:|---:|")
    L.append(f"| degenerate queries (one relevance level) | {dc['large_test_degenerate_count']:,} "
             f"({100*dc['large_test_degenerate_fraction']:.2f}%) | "
             f"{deg['test']['degenerate_count']:,} "
             f"({100*deg['test']['degenerate_fraction']:.2f}%) |")
    L.append(f"| all-I queries (IDCG == 0) | not measured | {deg['test']['all_I_count']:,} "
             f"({100*deg['test']['all_I_fraction']:.2f}%) |")
    L.append("")
    L.append(f"Expectation stated in section 11.3 — that the reduced version's degenerate share "
             f"should be **lower** than large-version's 21.06%, because 'easy' queries are "
             f"filtered out — is **{'MET' if dc['expectation_met'] else 'NOT MET'}**: "
             f"{100*deg['test']['degenerate_fraction']:.2f}% vs 21.06%.\n")

    L.append("## 5. Conclusion\n")
    L.append("Both benchmarks are internally valid and both remain usable for internal "
             "experiments on their own populations. Only the NEW benchmark corresponds to the "
             "KDD Cup 2022 Task 1 data definition and may be used as the reference for Task 1 "
             "work.\n")
    L.append("The OLD benchmark (`experiments/ranking_v2/official_metric_final/`) is **retained** "
             "as the LARGE-VERSION INTERNAL RANKING BENCHMARK. Its conclusions still hold on its "
             "own population. It must not be deleted, and its numbers must never be compared "
             "with, subtracted from, or quoted alongside Task 1 numbers — see the bookkeeping "
             "rule in section 16 of the REPORT.\n")
    L.append("Absolute NDCG on the NEW benchmark is expected to be lower than on the OLD one. "
             "That is a consequence of the benchmark definition changing (harder query subset, "
             "heavier JP weight, full-list rather than @10), **not** a regression and not a bug.\n")

    out = os.path.join(BASE, "benchmark_definition_comparison.md")
    with open(out, "w") as f:
        f.write("\n".join(L))
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
